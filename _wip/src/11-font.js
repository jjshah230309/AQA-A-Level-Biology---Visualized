const SUPMAP = { '²': '^2', '³': '^3', '⁴': '^4', '⁵': '^5', '⁺': '^+', '⁻': '^−', '⁰': '^0', '¹': '^1',
  '₂': '_2', '₃': '_3', '₁': '_1', '₄': '_4', '₀': '_0' };
const GLYPH_CACHE = new Map(), MISSING_GLYPHS = new Set();
function glyphStrokes(ch) {
  let g = GLYPH_CACHE.get(ch);
  if (g) return g;
  if (!GLYPHS[ch]) MISSING_GLYPHS.add(ch);
  const d = GLYPHS[ch] || GLYPHS['?'];
  g = { w: d[0], strokes: [] };
  for (let i = 1; i < d.length; i++) {
    let s = d[i], mode = 0;
    if (s[0] === 'c') { mode = 1; s = s.slice(1); } else if (s[0] === 'o') { mode = 2; s = s.slice(1); }
    const pts = [];
    s.trim().split(/\s+/).forEach(t => { const xy = t.split(','); pts.push(+xy[0], +xy[1]); });
    g.strokes.push({ mode, pts });
  }
  GLYPH_CACHE.set(ch, g);
  return g;
}
/* Parse label markup: ^x  _x  ^{...} _{...} -> array of {ch, lvl} (lvl 0 normal, 1 super, -1 sub) */
const NORM = { '\u2019': "'", '\u2018': "'", '\u201C': '"', '\u201D': '"', '\u2010': '-', '\u2011': '-', '\u2026': '...', '\u00A0': ' ', '\u2212': '\u2212' };
function parseLabel(str) {
  let s = '';
  for (const c of str) s += SUPMAP[c] || NORM[c] || c;
  const out = [];
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if ((c === '^' || c === '_') && i + 1 < s.length) {
      const lvl = c === '^' ? 1 : -1;
      if (s[i + 1] === '{') { const j = s.indexOf('}', i + 2); const body = s.slice(i + 2, j < 0 ? s.length : j); for (const b of body) out.push({ ch: b, lvl }); i = j < 0 ? s.length : j; }
      else { out.push({ ch: s[i + 1], lvl }); i++; }
    } else out.push({ ch: c, lvl: 0 });
  }
  return out;
}
function labelWidth(str, size) {
  const k = size / 7; let w = 0;
  for (const t of parseLabel(str)) { const g = glyphStrokes(t.ch); w += (g.w + 1.1) * k * (t.lvl ? 0.68 : 1); }
  return w;
}
